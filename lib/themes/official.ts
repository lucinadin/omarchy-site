import type { OmarchyThemeOption, ThemeMode } from "@/lib/themes/themes";

const officialThemePreviewsInImages = new Set(["last-horizon", "lupine", "solitude"]);

type ThemeColorValues = readonly [
  accent: string,
  selection: string,
  muted: string,
  background: string,
  darkBackground: string,
  darkerBackground: string,
  lighterBackground: string,
  foreground: string,
  darkForeground: string,
  lightForeground: string,
  brightForeground: string,
  red: string,
  yellow: string,
  orange: string,
  green: string,
  cyan: string,
  blue: string,
  magenta: string,
  brown: string,
  brightRed: string,
  brightYellow: string,
  brightGreen: string,
  brightCyan: string,
  brightBlue: string,
  brightMagenta: string,
];

function officialThemePreview(themeId: string) {
  return officialThemePreviewsInImages.has(themeId)
    ? `/assets/images/themes/${themeId}-preview.webp`
    : `/assets/manual/${themeId}-preview.webp`;
}

function officialThemeRepository(themeId: string) {
  return `https://github.com/omacom/omarchy/tree/quattro/themes/${themeId}`;
}

const theme = <const Id extends string>(
  id: Id,
  name: string,
  mode: ThemeMode,
  values: ThemeColorValues
): OmarchyThemeOption & { id: Id; kind: "official"; slug: Id } => {
  const [
    accent,
    selection,
    muted,
    background,
    darkBackground,
    darkerBackground,
    lighterBackground,
    foreground,
    darkForeground,
    lightForeground,
    brightForeground,
    red,
    yellow,
    orange,
    green,
    cyan,
    blue,
    magenta,
    brown,
    brightRed,
    brightYellow,
    brightGreen,
    brightCyan,
    brightBlue,
    brightMagenta,
  ] = values;

  return {
    colors: {
      accent,
      selection,
      muted,
      background,
      darkBackground,
      darkerBackground,
      lighterBackground,
      foreground,
      darkForeground,
      lightForeground,
      brightForeground,
      red,
      yellow,
      orange,
      green,
      cyan,
      blue,
      magenta,
      brown,
      brightRed,
      brightYellow,
      brightGreen,
      brightCyan,
      brightBlue,
      brightMagenta,
    },
    id,
    kind: "official",
    mode,
    name,
    preview: { image: officialThemePreview(id) },
    repository: officialThemeRepository(id),
    slug: id,
    wallpaper: "none",
  };
};

